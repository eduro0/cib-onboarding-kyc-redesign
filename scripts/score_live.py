"""Score the live replies in `assistant/live/` against the hand-written replies in `assistant/replays/`.

Implements: assistant/live-scored

Both replies go through the same rules (`assistant/rules.py`) with the same as-of date. A fact counts once it has
passed quote verification: an entity field, a director named in a given document, or a shareholding (owner, company
owned, percent). For each live reply the score gives:
- claimed: facts the model put forward; kept: facts that passed verification; dropped: claimed minus kept;
- missed: verified facts of the hand-written reply that the live reply doesn't have; extra: the reverse;
- flags_same: the rules raise the same flags (rule and wording); request_same: the client request has the same
  wording. Both comparisons ignore letter case and punctuation, as the rules do: the prompt asks for names as the
  document writes them, so a model may write CHAN WING-YEE where the hand-written reply has Chan Wing-yee.
`make build` writes `assistant/live/results.md` and adds the totals per model to `build/numbers.json`.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from assistant import llm, rules  # noqa: E402

SAMPLES = ROOT / "assistant" / "samples"
LIVE = ROOT / "assistant" / "live"
AS_OF = date(2026, 11, 18)  # the date the sample packs and the tests are set at


def facts(result: rules.Result) -> set[tuple]:
    out = {("entity", k, rules.norm(str(v["value"]))) for k, v in result.entity.items()}
    out |= {("director", doc, rules.norm(n)) for doc, names in result.directors.items() for n in names}
    out |= {("ownership", rules.norm(h.owner), rules.norm(h.owned), h.percent) for h in result.ownership}
    return out


def claimed(reply: dict) -> int:
    return len(reply.get("entity") or {}) + len(reply.get("director_mentions") or []) + len(reply.get("ownership") or [])


def score(folder: Path, reply: dict | None) -> dict:
    reply = reply or {}
    key = rules.evaluate(folder, llm.replay(folder), AS_OF)
    live = rules.evaluate(folder, reply, AS_OF)
    want, got = facts(key), facts(live)
    kept = len(live.entity) + sum(len(n) for n in live.directors.values()) + len(live.ownership)
    flag_set = lambda r: sorted((f.rule, rules.norm(f.reason)) for f in r.flags)  # noqa: E731
    return {"claimed": claimed(reply), "kept": kept, "dropped": claimed(reply) - kept, "key_facts": len(want),
            "found": len(want & got), "missed": len(want - got),
            "missed_entity": sum(1 for f in want - got if f[0] == "entity"), "extra": len(got - want),
            "flags_same": flag_set(key) == flag_set(live), "request_same": rules.norm(key.client_request or "") == rules.norm(live.client_request or ""),
            "flag_diff": sorted((Counter(f.rule for f in live.flags) - Counter(f.rule for f in key.flags)).elements()),
            "flag_lost": sorted((Counter(f.rule for f in key.flags) - Counter(f.rule for f in live.flags)).elements())}


def recordings() -> list[tuple[str, dict, dict]]:
    """(pack, recording, score) for every recorded live reply, in a fixed order."""
    out = []
    for path in sorted(LIVE.glob("*/*.json")):
        rec = json.loads(path.read_text(encoding="utf-8"))
        out.append((path.parent.name, rec, score(SAMPLES / path.parent.name, rec["reply"])))
    return out


def numbers() -> dict:
    out: dict = {}
    for _, rec, s in recordings():
        m = llm_slug(rec["model"])
        t = out.setdefault(m, Counter())
        t.update({"packs": 1, "key_facts": s["key_facts"], "found": s["found"], "missed": s["missed"],
                  "missed_entity": s["missed_entity"], "dropped": s["dropped"], "flags_same": int(s["flags_same"]), "request_same": int(s["request_same"]),
                  "cost_micro_usd": round(rec["cost_usd"] * 1e6)})
    flat = {}
    for m, t in out.items():
        for k, v in t.items():
            flat[f"live.{m}.{k}"] = v
        flat[f"live.{m}.cost_usd"] = round(t["cost_micro_usd"] / 1e6, 4)
        del flat[f"live.{m}.cost_micro_usd"]
    return flat


def llm_slug(model: str) -> str:
    return model.split("/")[-1].replace(":", "-").replace(".", "-")


def render() -> str:
    lines = ["<!-- Implements: assistant/live-scored -->",
             "<!-- Generated by scripts/score_live.py (make build). Do not edit by hand. -->",
             "# Live runs, scored against the hand-written replies", "",
             f"Each sample pack was sent to real models on OpenRouter with the prompt in `prompts/extract.md`. Each reply "
             f"went through the same rules as the hand-written reply in `assistant/replays/`, as of {AS_OF}. "
             "A fact counts once it passes quote verification. \"Found\" is how many of the hand-written reply's "
             "verified facts the model also produced; \"dropped\" is how many of the model's facts failed verification. "
             "Flags and the client request are compared ignoring letter case and punctuation.",
             "", "| Pack | Model | Date | Found / key facts | Missed | Extra | Dropped | Same flags | Same client request | Tokens in / out | Cost (USD) |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    notes = []
    for pack, rec, s in recordings():
        lines.append(f"| {pack} | `{rec['model']}` | {rec['date']} | {s['found']} / {s['key_facts']} | {s['missed']} | "
                     f"{s['extra']} | {s['dropped']} | {'yes' if s['flags_same'] else 'no'} | "
                     f"{'yes' if s['request_same'] else 'no'} | {rec['prompt_tokens']} / {rec['completion_tokens']} | "
                     f"{rec['cost_usd']:.4f} |")
        if rec["reply"] is None:
            notes.append(f"- {pack}, `{rec['model']}`: the reply wasn't JSON, so nothing was extracted.")
        if not s["flags_same"] and not (s["flag_diff"] or s["flag_lost"]):
            notes.append(f"- {pack}, `{rec['model']}`: the same kinds of flag, worded differently.")
        if s["flag_diff"] or s["flag_lost"]:
            notes.append(f"- {pack}, `{rec['model']}`: extra flags {s['flag_diff'] or 'none'}; flags not raised "
                         f"{s['flag_lost'] or 'none'}.")
    if notes:
        lines += ["", "Where the flags differ from the hand-written reply's:", "", *notes]
    packs = len({pack for pack, _, _ in recordings()})
    lines += ["", f"{packs} small fictional packs show that a real model's output works with the rules. They don't "
                  "measure accuracy.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    (LIVE / "results.md").write_text(render(), encoding="utf-8")
    print(json.dumps(numbers(), indent=1))
