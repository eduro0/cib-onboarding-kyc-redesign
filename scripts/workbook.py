"""The KPI workbook (deliverables/kpi-model.xlsx), shaped to import into Google Sheets as it is.

Implements: kpi-model/sheets-ready, kpi-model/assumptions-visible, kpi-model/baseline-vs-to-be

Tabs: Read me, Assumptions (every input with unit and basis), Cases (one row per simulated case), KPIs (live
formulas over Cases, so the numbers recompute in Sheets if a case is edited, next to the values Python computed)
and Looker data (one row per case and KPI, the long shape Looker Studio charts best). Row 1 of every tab says the
data is simulated.
"""

from __future__ import annotations

import re
import zipfile
from datetime import datetime
from pathlib import Path

import yaml
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

ROOT = Path(__file__).resolve().parent.parent
BANNER = ("SIMULATED DATA. Illustrative model of a CIB branch in Hong Kong: the process maps are drawn from public "
          "rules; every model input is a labelled guess (Assumptions tab). Not real bank data.")
HEAD = PatternFill("solid", fgColor="DDE3EA")
CASE_COLS = ["Case", "Process", "Case type", "Cycle days", "Touch hours", "Rework loops", "Client touches",
             "First pass", "Declined", "On time"]
KPI_ROWS = [("Cycle time", "cycle_days", "days", "AVERAGEIFS", "D", "Mean elapsed days from first request to account live / file current"),
            ("Touch time", "touch_hours", "staff hours", "AVERAGEIFS", "E", "Mean hands-on staff hours per case"),
            ("First-pass rate", "first_pass", "share", "AVERAGEIFS", "H", "Share of cases with no rework loop"),
            ("Rework", "rework", "loops per case", "AVERAGEIFS", "F", "Mean times a case went back a step"),
            ("Client touches", "client_touches", "asks per case", "AVERAGEIFS", "G", "Mean separate requests sent to the client")]


def banner(ws, text: str = BANNER) -> None:
    ws["A1"] = text
    ws["A1"].font = Font(bold=True, color="C0392B")


def header(ws, row: int, names: list[str]) -> None:
    for i, name in enumerate(names, 1):
        cell = ws.cell(row=row, column=i, value=name)
        cell.font, cell.fill = Font(bold=True), HEAD


def widths(ws, values: list[int]) -> None:
    for i, w in enumerate(values, 1):
        ws.column_dimensions[get_column_letter(i)].width = w


def write(cases: list[dict], numbers: dict, path: Path) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "Read me"
    banner(ws)
    lines = ["", "What this is",
             "A KPI model for the AI-first redesign of corporate client onboarding and periodic KYC review.",
             "Simulated cases walk the steps of the As-Is and To-Be BPMN maps; every input is on the Assumptions tab.",
             "", "Tabs",
             "Assumptions: every input, with its unit and its basis (a source, or (guess) for a judgment call).",
             "Cases: one row per simulated case. Edit a row and the KPIs tab recomputes.",
             "KPIs: As-Is vs To-Be per case type, as live formulas over Cases.",
             "Looker data: one row per case and KPI, for the Looker Studio dashboard.",
             "", "How the As-Is compares with public benchmarks (vendor surveys, none sampled in Hong Kong)",
             f"Simulated As-Is onboarding: {numbers['onb_cycle_days_as_is']} days on average; "
             f"{numbers['onb_over_60_days_as_is']:.0%} of cases take more than 60 days.",
             "Thomson Reuters 2016: 30% of corporates said onboarding took more than two months; 2017: banks reported 30 days on average.",
             "Fenergo 2025: UK corporate banks average more than six weeks; Fenergo 2023: US investment banks a mean of 82 days per KYC review.",
             "The As-Is inputs are guesses set so the simulated baseline sits inside that public range; Phase 0 of the roadmap replaces them with measured times.",
             "", "Remake it", "The model and this file are generated by scripts/build.py from model/*.yaml with a fixed seed."]
    for i, line in enumerate(lines, 2):
        ws.cell(row=i, column=1, value=line).font = Font(bold=line in {"What this is", "Tabs", "Remake it"} or line.startswith("How the As-Is"))
    widths(ws, [120])

    ws = wb.create_sheet("Assumptions")
    banner(ws, "SIMULATED inputs. Each basis is a source key or (guess).")
    header(ws, 2, ["Group", "Key", "Value", "Unit", "Basis", "Note"])
    raw = yaml.safe_load((ROOT / "model" / "assumptions.yaml").read_text(encoding="utf-8"))
    r = 3
    for group, items in raw.items():
        for key, a in items.items():
            value = a["value"] if not isinstance(a["value"], (dict, list)) else str(a["value"])
            for c, v in enumerate([group, key, value, a["unit"], a["basis"], a.get("note", "")], 1):
                ws.cell(row=r, column=c, value=v)
            r += 1
    widths(ws, [10, 30, 22, 14, 22, 80])

    ws = wb.create_sheet("Cases")
    banner(ws, "SIMULATED cases, one per row.")
    header(ws, 2, CASE_COLS)
    for r, c in enumerate(cases, 3):
        row = [c["id"], c["process"], c["case_type"], round(c["cycle_days"], 2), round(c["touch_hours"], 2),
               c["rework"], c["client_touches"], int(c["first_pass"]), int(c["declined"]),
               "" if "on_time" not in c else int(c["on_time"])]
        for col, v in enumerate(row, 1):
            ws.cell(row=r, column=col, value=v)
    ws.freeze_panes = "A3"
    widths(ws, [11, 9, 12, 11, 12, 12, 13, 10, 9, 8])

    ws = wb.create_sheet("KPIs")
    banner(ws, "SIMULATED KPIs. Columns C-D are live formulas over the Cases tab; F-G are the values the model computed.")
    header(ws, 2, ["KPI", "Case type", "As-Is (formula)", "To-Be (formula)", "Change", "As-Is (model)", "To-Be (model)", "Unit", "Definition"])
    r = 3
    last = len(cases) + 2
    for case_type, short in (("onboarding", "onb"), ("review", "rev")):
        rows = KPI_ROWS + ([("Reviews on time", "on_time", "share", "AVERAGEIFS", "J", "Share of reviews finished within the review lead time")] if case_type == "review" else [])
        for label, key, unit, _, col, definition in rows:
            def formula(process: str) -> str:
                return (f'=AVERAGEIFS(Cases!{col}3:{col}{last},Cases!B3:B{last},"{process}",'
                        f'Cases!C3:C{last},"{case_type}",Cases!I3:I{last},0)')
            ws.cell(row=r, column=1, value=label)
            ws.cell(row=r, column=2, value=case_type)
            ws.cell(row=r, column=3, value=formula("as-is"))
            ws.cell(row=r, column=4, value=formula("to-be"))
            if unit == "share":  # a share changes in percentage points
                ws.cell(row=r, column=5, value=f"=(D{r}-C{r})*100").number_format = '+0" pts";-0" pts"'
            else:
                ws.cell(row=r, column=5, value=f"=IF(C{r}=0,\"\",(D{r}-C{r})/C{r})").number_format = "+0%;-0%"
            ws.cell(row=r, column=6, value=numbers[f"{short}_{key}_as_is"] if key != "on_time" else numbers["rev_on_time_as_is"])
            ws.cell(row=r, column=7, value=numbers[f"{short}_{key}_to_be"] if key != "on_time" else numbers["rev_on_time_to_be"])
            ws.cell(row=r, column=8, value=unit)
            ws.cell(row=r, column=9, value=definition)
            for c in (3, 4, 6, 7):
                ws.cell(row=r, column=c).number_format = "0%" if unit == "share" else "0.0"
            r += 1
    r += 1
    ws.cell(row=r, column=1, value="Sensitivity").font = Font(bold=True)
    r += 1
    ws.cell(row=r, column=1, value="If every To-Be human step kept today's queue time, To-Be cycle time would be:")
    for case_type, short in (("onboarding", "onb"), ("review", "rev")):
        r += 1
        ws.cell(row=r, column=1, value="Cycle time, today's queues")
        ws.cell(row=r, column=2, value=case_type)
        ws.cell(row=r, column=6, value=numbers[f"{short}_cycle_days_as_is"])
        ws.cell(row=r, column=7, value=numbers[f"{short}_cycle_days_to_be_slow_queues"])
        ws.cell(row=r, column=8, value="days")
        ws.cell(row=r, column=9, value="Shows how much of the cycle-time gain depends on shorter queues, which are assumed, not designed")
    widths(ws, [26, 12, 16, 16, 9, 14, 14, 15, 70])

    ws = wb.create_sheet("Looker data")
    banner(ws, "SIMULATED data in long form for Looker Studio: one row per case and KPI.")
    header(ws, 2, ["Case", "Process", "Case type", "KPI", "Value"])
    r = 3
    for c in cases:
        if c["declined"]:
            continue
        values = {"Cycle time (days)": c["cycle_days"], "Touch time (hours)": c["touch_hours"],
                  "First pass (1 = yes)": int(c["first_pass"]), "Rework loops": c["rework"],
                  "Client touches": c["client_touches"]}
        if "on_time" in c:
            values["On time (1 = yes)"] = int(c["on_time"])
        for kpi, v in values.items():
            for col, val in enumerate([c["id"], "As-Is" if c["process"] == "as-is" else "To-Be", c["case_type"], kpi,
                                       round(v, 2)], 1):
                ws.cell(row=r, column=col, value=val)
            r += 1
    widths(ws, [11, 9, 12, 22, 10])
    for sheet in wb.worksheets:
        sheet["A1"].alignment = Alignment(wrap_text=False)
    fixed = datetime(2026, 11, 18)  # fixed file dates, so a remade workbook is byte-identical
    wb.properties.created = wb.properties.modified = fixed
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    with zipfile.ZipFile(path) as z:  # openpyxl stamps the save time into docProps/core.xml; rewrite it fixed
        parts = {n: z.read(n) for n in z.namelist()}
    core = re.sub(rb"(<dcterms:modified[^>]*>)[^<]*(</dcterms:modified>)", rb"\g<1>2026-11-18T00:00:00Z\g<2>",
                  parts["docProps/core.xml"])
    parts["docProps/core.xml"] = core
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        for n, data in parts.items():
            info = zipfile.ZipInfo(n, date_time=(2026, 11, 18, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, data)
